// Exercise #4: Displaying Restaurant Name
let restaurants = ["KFC", "MOMO PARADISE", "Nabezo"];
let newRestaurants = [];
for (let i = 0; i < restaurants.length; i++) {
    newRestaurants+=(" Restaurant Name: " + restaurants[i]);
}
console.log(newRestaurants);// Output: Restaurant Name: KFC Restaurant Name: MOMO PARADISE Restaurant Name: Nabezo
